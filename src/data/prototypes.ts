export interface ProtoLine {
  id: string;
  /** 話す人（キャラの id）。null なら地の文 */
  speaker: 'hero' | 'akari' | null;
  text: string;
  /** 話す人の表情（この行から変わる。書かなければ前の行のまま） */
  face?: AkariFace | HeroFace;
  /** 次の行（なければ台本の順で次） */
  next?: string;
  /** 選択肢（あれば、選んだ先へ進む） */
  choices?: { label: string; next: string }[];
  /** これで終わり */
  end?: boolean;
}

