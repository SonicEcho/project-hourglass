/** 文字の地図の一部を書き換える（試しの区画で、今の地図に出入口の道を開ける。S は消す） */
function carve(layout: string[], open: [col: number, row: number][], dropStart = false): string[] {
  const rows = layout.map((l) => [...(dropStart ? l.replace('S', '.') : l)]);
  for (const [c, r] of open) rows[r][c] = '.';
  return rows.map((r) => r.join(''));
}
/** 長方形のマスの並び（列 c0〜c1、行 r0〜r1） */
export function box(c0: number, c1: number, r0: number, r1: number): [number, number][] {
  const out: [number, number][] = [];
  for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) out.push([c, r]);
  return out;
}

/** 文字の地図のマスを、決めた記号に書き換える（[列, 行, 記号]） */
function setCells(layout: string[], cells: [col: number, row: number, ch: string][]): string[] {
  const rows = layout.map((l) => [...l]);
  for (const [c, r, ch] of cells) rows[r][c] = ch;
  return rows.map((r) => r.join(''));
}

