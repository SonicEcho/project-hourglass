from PIL import Image, ImageDraw, ImageFont

T = 34
F = ImageFont.truetype('/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf', 15)
FB = ImageFont.truetype('/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf', 22)
C = {'#': (34, 40, 52), '.': (176, 150, 120), 's': (168, 160, 150), 'F': (226, 92, 70), 'B': (150, 120, 90), 'x': (74, 150, 222), 'y': (120, 96, 70), 'h': (150, 90, 190), 'g': (230, 190, 80), 'k': (92, 128, 70)}
LEGEND = [('#', '家の屋根・塀・木（通れない）'), ('.', '道（アスファルト・土）'), ('s', '石畳・石段'), ('F', '店の表が立つ所（道を向く）'), ('B', '店の裏が立つ所'), ('y', '空き地・裏庭'), ('g', 'アーケードの門（下を通れる）'), ('k', '植え込み・草'), ('h', '寄り道の隅（誘導なし）'), ('x', '出入口')]


def plan(name, title, rows, labels):
    assert len(rows) == 24 and all(len(r) == 24 for r in rows), name
    w = 24 * T
    im = Image.new('RGB', (w + 330, w + 50), (20, 22, 30))
    d = ImageDraw.Draw(im)
    d.text((10, 10), title, font=FB, fill=(240, 240, 240))
    for y, line in enumerate(rows):
        for x, ch in enumerate(line):
            d.rectangle([x * T, 46 + y * T, (x + 1) * T - 1, 46 + (y + 1) * T - 1], fill=C[ch])
    for k in range(25):
        d.line([k * T, 46, k * T, 46 + w], fill=(0, 0, 0))
        d.line([0, 46 + k * T, w, 46 + k * T], fill=(0, 0, 0))
    for (x, y, t) in labels:
        d.text((x * T + 2, 46 + y * T + 4), t, font=F, fill=(255, 255, 255), stroke_width=2, stroke_fill=(0, 0, 0))
    ly = 60
    for ch, t in LEGEND:
        d.rectangle([w + 20, ly, w + 44, ly + 24], fill=C[ch])
        d.text((w + 52, ly + 2), t, font=F, fill=(230, 230, 230))
        ly += 36
    im.save(f'docs/sketches/a12_v1/{name}_plan.png')


